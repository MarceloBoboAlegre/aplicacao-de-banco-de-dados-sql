-- ELIMINANDO AS TABELAS CASO EXISTAM
 DROP TABLE IF EXISTS tb_vendas_lanches_pbi;
 DROP TABLE IF EXISTS tb_produtos_lanches_pbi;

-- CRIANDO A TABELA DE PRODUTOS
CREATE TABLE tb_produtos_lanches_pbi (
    id_produto INT PRIMARY KEY,
    nome VARCHAR(100),
    categoria VARCHAR(50),
    preco DECIMAL(10,2)
);

-- CRIANDO A TABELA DE VENDAS
CREATE TABLE tb_vendas_lanches_pbi (
    id_venda INT PRIMARY KEY,
    data_venda DATE,
    id_produto INT,
    quantidade INT,
    forma_pagamento VARCHAR(20),
    avaliacao INT,
    FOREIGN KEY (id_produto) REFERENCES tb_produtos_lanches_pbi(id_produto)
);

